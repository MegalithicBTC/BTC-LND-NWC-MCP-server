#!/usr/bin/env node
/**
 * Setup GUI server — `npm run setup`.
 *
 * Serves a single-page configuration UI on localhost only:
 *   - GET  /api/config  read current settings (.env + defaults)
 *   - POST /api/test    connect to the wallet with the submitted settings
 *   - POST /api/save    write settings to <project>/.env
 *
 * Security: binds to 127.0.0.1, denies non-local requests, and sends
 * no data anywhere except your own wallet backend during "Test".
 */
import { createServer, type IncomingMessage, type ServerResponse } from "node:http";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { spawn } from "node:child_process";
import { SETUP_PAGE } from "./page.js";
import { generateFullNodeStack } from "./fullnode.js";
import {
  bitcoindInfo,
  checkPrereqs,
  composeAction,
  lndAction,
  lndCredentials,
} from "./nodeops.js";
import { loadDotEnv, envFilePath, packageRoot } from "../env.js";
import { loadConfig, createBackend, type Settings } from "../config.js";

const PORT = Number(process.env.SETUP_PORT ?? 8642);
const serverEntry = join(packageRoot, "dist", "index.js");

const json = (res: ServerResponse, code: number, payload: unknown): void => {
  res.writeHead(code, { "Content-Type": "application/json" });
  res.end(JSON.stringify(payload));
};

const readBody = (req: IncomingMessage): Promise<string> =>
  new Promise((resolve, reject) => {
    let body = "";
    req.on("data", (chunk: Buffer) => {
      body += chunk.toString();
      if (body.length > 1_000_000) reject(new Error("body too large"));
    });
    req.on("end", () => resolve(body));
    req.on("error", reject);
  });

function sanitizeSettings(raw: unknown): Settings {
  const s = raw as Partial<Settings>;
  const backend = s.backend === "lnd" ? "lnd" : "nwc";
  const nonNeg = (v: unknown, fallback: number): number => {
    const n = Number(v);
    return Number.isFinite(n) && n >= 0 ? n : fallback;
  };
  return {
    backend,
    nwcConnectionString: String(s.nwcConnectionString ?? "").trim() || undefined,
    lndRestUrl: String(s.lndRestUrl ?? "").trim() || undefined,
    lndMacaroonHex: String(s.lndMacaroonHex ?? "").trim() || undefined,
    lndTlsCertPath: String(s.lndTlsCertPath ?? "").trim() || undefined,
    lndSkipCertVerify: Boolean(s.lndSkipCertVerify),
    maxSendSats: nonNeg(s.maxSendSats, 10_000),
    dailyBudgetSats: nonNeg(s.dailyBudgetSats, 50_000),
    maxFeePercent: nonNeg(s.maxFeePercent, 1),
    defaultInvoiceExpiry: Math.max(60, nonNeg(s.defaultInvoiceExpiry, 3600)),
  };
}

function renderEnv(s: Settings): string {
  const lines = [
    "# Generated by the btc-mcp-srv setup GUI (npm run setup)",
    `# ${new Date().toISOString()}`,
    "",
    `LN_BACKEND=${s.backend}`,
    "",
    `NWC_CONNECTION_STRING=${s.nwcConnectionString ?? ""}`,
    "",
    `LND_REST_URL=${s.lndRestUrl ?? ""}`,
    `LND_MACAROON_HEX=${s.lndMacaroonHex ?? ""}`,
    `LND_TLS_CERT_PATH=${s.lndTlsCertPath ?? ""}`,
    `LND_SKIP_CERT_VERIFY=${s.lndSkipCertVerify ? "true" : "false"}`,
    "",
    `MAX_SEND_SATS=${s.maxSendSats}`,
    `DAILY_BUDGET_SATS=${s.dailyBudgetSats}`,
    `MAX_FEE_PERCENT=${s.maxFeePercent}`,
    `DEFAULT_INVOICE_EXPIRY=${s.defaultInvoiceExpiry}`,
    "",
  ];
  return lines.join("\n");
}

async function handleTest(res: ServerResponse, raw: string): Promise<void> {
  let settings: Settings;
  try {
    settings = sanitizeSettings(JSON.parse(raw));
  } catch {
    return json(res, 400, { ok: false, error: "invalid request body" });
  }
  try {
    const backend = createBackend(settings);
    try {
      const balance = await Promise.race([
        backend.getBalance(),
        new Promise<never>((_, reject) =>
          setTimeout(
            () => reject(new Error("timed out after 20s — check the connection details")),
            20_000,
          ),
        ),
      ]);
      json(res, 200, {
        ok: true,
        backend: backend.name,
        balanceSats: balance.balanceSats,
      });
    } finally {
      await backend.close().catch(() => undefined);
    }
  } catch (err) {
    json(res, 200, {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    });
  }
}

function handleSave(res: ServerResponse, raw: string): void {
  let settings: Settings;
  try {
    settings = sanitizeSettings(JSON.parse(raw));
  } catch {
    return json(res, 400, { ok: false, error: "invalid request body" });
  }
  try {
    writeFileSync(envFilePath, renderEnv(settings), { mode: 0o600 });
    json(res, 200, { ok: true, path: envFilePath });
  } catch (err) {
    json(res, 200, {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    });
  }
}

function handleFullnode(res: ServerResponse, raw: string): void {
  let body: unknown;
  try {
    body = JSON.parse(raw);
  } catch {
    return json(res, 400, { ok: false, error: "invalid request body" });
  }
  try {
    const stack = generateFullNodeStack(body);
    const dir = join(packageRoot, "fullnode");
    const written: string[] = [];
    const overwritten: string[] = [];
    for (const file of stack.files) {
      const abs = join(dir, file.relPath);
      const existed = existsSync(abs);
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, file.content, { mode: file.mode ?? 0o644 });
      (existed ? overwritten : written).push(file.relPath);
    }
    json(res, 200, {
      ok: true,
      dir,
      written,
      overwritten,
      commands: stack.commands,
      notes: stack.notes,
    });
  } catch (err) {
    json(res, 200, {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    });
  }
}

// Hosts a local browser is allowed to reach us as. Rejecting anything else
// defeats DNS-rebinding attacks (a malicious site re-pointing its own domain
// at 127.0.0.1 to read this API "same-origin" — its Host header would still
// carry the attacker's domain).
const ALLOWED_HOSTS = new Set([
  `127.0.0.1:${PORT}`,
  `localhost:${PORT}`,
  `[::1]:${PORT}`,
  "127.0.0.1",
  "localhost",
  "[::1]",
]);

const server = createServer(async (req, res) => {
  const host = (req.headers.host ?? "").toLowerCase();
  if (!ALLOWED_HOSTS.has(host)) {
    return json(res, 403, { ok: false, error: "invalid Host header" });
  }
  // Same-origin browser requests only; block anything cross-site.
  const fetchSite = req.headers["sec-fetch-site"];
  if (fetchSite && fetchSite !== "same-origin" && fetchSite !== "none") {
    return json(res, 403, { ok: false, error: "cross-site request denied" });
  }

  const url = req.url ?? "/";
  try {
    if (req.method === "GET" && (url === "/" || url === "/index.html")) {
      res.writeHead(200, {
        "Content-Type": "text/html; charset=utf-8",
        "Cache-Control": "no-store",
        "X-Content-Type-Options": "nosniff",
      });
      return res.end(
        SETUP_PAGE.replace("__SERVER_PATH__", serverEntry.replace(/\\/g, "\\\\")),
      );
    }
    if (req.method === "GET" && url === "/api/config") {
      loadDotEnv();
      return json(res, 200, loadConfig());
    }
    if (req.method === "POST" && url === "/api/test") {
      return await handleTest(res, await readBody(req));
    }
    if (req.method === "POST" && url === "/api/save") {
      return handleSave(res, await readBody(req));
    }
    if (req.method === "POST" && url === "/api/fullnode") {
      return handleFullnode(res, await readBody(req));
    }
    if (req.method === "GET" && url === "/api/node/prereqs") {
      return json(res, 200, { ok: true, ...(await checkPrereqs()) });
    }
    if (req.method === "POST" && url === "/api/node/compose") {
      const b = JSON.parse(await readBody(req)) as {
        action?: string;
        service?: string;
      };
      if (!["up", "down", "ps", "logs"].includes(b.action ?? "")) {
        return json(res, 400, { ok: false, error: "invalid compose action" });
      }
      const r = await composeAction(
        b.action as "up" | "down" | "ps" | "logs",
        b.service,
      );
      return json(res, 200, {
        ok: r.ok,
        output: r.ok ? r.stdout : r.stderr,
        containers: r.containers,
        error: r.ok ? undefined : r.stderr.trim() || "command failed",
      });
    }
    if (req.method === "GET" && url === "/api/node/bitcoind") {
      return json(res, 200, await bitcoindInfo());
    }
    if (req.method === "POST" && url === "/api/node/lnd") {
      const b = JSON.parse(await readBody(req)) as {
        action?: string;
        password?: string;
        seed?: string[];
      };
      try {
        const result = await lndAction(String(b.action ?? ""), {
          password: b.password,
          seed: b.seed,
        });
        return json(res, 200, { ok: true, result });
      } catch (err) {
        return json(res, 200, {
          ok: false,
          error: err instanceof Error ? err.message : String(err),
        });
      }
    }
    if (req.method === "GET" && url === "/api/node/lndcreds") {
      return json(res, 200, { ok: true, ...lndCredentials() });
    }
    json(res, 404, { ok: false, error: "not found" });
  } catch (err) {
    json(res, 500, {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    });
  }
});

server.listen(PORT, "127.0.0.1", () => {
  const url = `http://127.0.0.1:${PORT}`;
  console.log(`\n  ⚡ btc-mcp-srv setup GUI running at ${url}\n`);
  console.log("  Configure your wallet, test the connection, save — then");
  console.log("  restart your MCP client. Press Ctrl+C here when done.\n");

  // Best-effort: open the default browser.
  const cmd =
    process.platform === "win32"
      ? { bin: "cmd", args: ["/c", "start", "", url] }
      : process.platform === "darwin"
        ? { bin: "open", args: [url] }
        : { bin: "xdg-open", args: [url] };
  try {
    spawn(cmd.bin, cmd.args, { stdio: "ignore", detached: true }).unref();
  } catch {
    /* user can open the URL manually */
  }
});
